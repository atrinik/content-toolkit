def short(path: str) -> str:
    return path[len(OW_PREFIX):] if path and path.startswith(OW_PREFIX) else (path or "")


def base(path: str) -> str:
    return path.rsplit("/", 1)[-1] if path else ""


def ow_name(x, y, z):
    X, Y = x // 24, y // 24
    return "world_{}_{}{} ({},{})".format(X, Y, "" if z == 0 else "_{}".format(z), x - 24 * X, y - 24 * Y)


def layers_of(bb: dict) -> str:
    ls = sorted(int(k) for k in bb)
    return str(ls[0]) if len(ls) == 1 else "{}..{}".format(ls[0], ls[-1])


def crossing(g):
    for key in ("entrances_from_overworld", "exits_to_overworld", "entrances_from_other_groups",
                "exits_to_other_groups"):
        for e in g.get(key, []):
            yield key, e


def becomes_counts(g):
    c = collections.Counter()
    seen = set()
    for _, e in crossing(g):
        k = (e["source_map"], e["line"])
        if k in seen or "becomes" not in e:
            continue
        seen.add(k)
        c[e["becomes"]] += 1
    return c


ORDER = ("stairs", "stairwell", "portal", "same-tile")


def fmt_counts(c):
    return ", ".join("{} {}".format(c[k], k) for k in ORDER if c.get(k))


def owner_name(o, lab):
    if o in lab:
        return "#{} `{}`".format(lab[o], base(o))
    return "`{}`".format(base(o))


