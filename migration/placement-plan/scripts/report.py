def short(path: str) -> str:
    return path[len(OW_PREFIX):] if path and path.startswith(OW_PREFIX) else (path or "")


def base(path: str) -> str:
    return path.rsplit("/", 1)[-1] if path else ""


def layers_of(bb: dict) -> str:
    ls = sorted(int(k) for k in bb)
    return str(ls[0]) if len(ls) == 1 else "{}..{}".format(ls[0], ls[-1])


def crossing(g):
    for key in ("entrances_from_overworld", "exits_to_overworld", "entrances_from_other_groups",
                "exits_to_other_groups"):
        for e in g.get(key, []):
            yield key, e


def becomes_counts(g):
    c = collections.Counter()
    seen = set()
    for _, e in crossing(g):
        k = (e["source_map"], e["line"])
        if k in seen or "becomes" not in e:
            continue
        seen.add(k)
        c[e["becomes"]] += 1
    return c


ORDER = ("stairs", "stairwell", "portal", "same-tile")


def fmt_counts(c):
    return ", ".join("{} {}".format(c[k], k) for k in ORDER if c.get(k))


def owner_name(o, lab):
    if o in lab:
        return "#{} `{}`".format(lab[o], base(o))
    return "`{}`".format(base(o))


def tile_name(m, t):
    return "{} ({},{})".format(base(m), t[0], t[1])


def plane_name(m, x, y):
    """Legacy tile name of plane tile (x, y) of overworld map m."""
    tail = base(m).split("_")
    X, Y = int(tail[1]), int(tail[2])
    return "{} ({},{})".format(base(m), x - 24 * X, y - 24 * Y)


def num(n):
    return "{:,}".format(n)


def end_name(sw, which):
    """Legacy name of a stairwell's top or bottom end, from the exits it replaces."""
    t = sw["tiles"][0] if which == "top" else sw["tiles"][-1]
    for r in sw["replaces"]:
        for pkey, mkey, tkey in (("plane_source", "source_map", "source_tile"),
                                 ("plane_target", "target_map", "target_tile")):
            if r[pkey] == [t["x"], t["y"], t["layer"]]:
                return tile_name(r[mkey], r[tkey])
    return "({}, {})".format(t["x"], t["y"])


