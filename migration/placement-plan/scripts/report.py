    seen = set()
    for g in groups:
        for _, e in crossing(g):
            k = (e["source_map"], e["line"])
            if k in seen or e.get("becomes") != "portal":
                continue
            seen.add(k)
            agg[(base(e["source_map"]), base(e["target_map"]), e["xy_distance"], abs(e["layer_delta"]),
                 e["portal_reason"] + (", slope" if e.get("slope_reachable") else ""))] += 1
    for (a, b, d, dl, why), n in sorted(agg.items()):
        w("| {} -> {} | {} | {} | {} | {} |".format(a, b, n, d, dl, why))
