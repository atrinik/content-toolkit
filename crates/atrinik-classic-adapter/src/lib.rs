/// Compare the WHOLE validated World, permitting only eligible coordinates.
/// `current_documents` must contain the entire authoritative source inventory;
/// callers obtain it with bounded rooted enumeration (not manifest paths).
pub fn preview_export(
    source: &Document,
    baseline: &VerifiedBaseline,
    current: &World,
    expected_world: [u8; 32],
    current_documents: &BTreeMap<String, Vec<u8>>,
) -> Result<ExportPreview> {
    if current.source_digest() != expected_world {
        return Err(error("stale current World revision"));
    }
    if source.revision().to_string() != baseline.bundle.manifest.identity.original_sha256 {
        return Err(error("stale original revision"));
    }
    let mut mappings = baseline.bundle.manifest.mappings.clone();
    if current.object_uids().len() != mappings.len() {
        return Err(error("unsupported added/deleted/inventory UID"));
    }
    let dimensions = baseline.bundle.manifest.dimensions;
    for m in &mut mappings {
        let object = current
            .object(&m.uid)
            .ok_or_else(|| error("missing original UID"))?;
        let location = current
            .object_location(&m.uid)
            .ok_or_else(|| error("missing UID location"))?;
        if location.plane != "main" || location.chunk.0 != 0 || location.path.len() != 1 {
            return Err(error("unsupported plane/layer/inventory move"));
        }
        let at = object
            .at
            .ok_or_else(|| error("missing placed-object coordinate"))?;
        let x = location
            .chunk
            .1
            .checked_mul(32)
            .and_then(|v| v.checked_add(i64::from(at[0])))
            .ok_or_else(|| error("coordinate overflow"))?;
        let y = location
            .chunk
            .2
            .checked_mul(32)
            .and_then(|v| v.checked_add(i64::from(at[1])))
            .ok_or_else(|| error("coordinate overflow"))?;
        if x < 0 || y < 0 || x >= dimensions[0] || y >= dimensions[1] {
            return Err(error("move outside original bounds"));
        }
        if [x, y] != m.at && !m.movable {
            return Err(error(
                "source coordinates omitted/repeated; move unsupported",
            ));
        }
        m.at = [x, y];
    }
    let expected_files = project(&mappings, dimensions)?;
    // Full canonical DOCUMENT comparison catches metadata/custom/schema and
    // structural changes even when a typed projection omits a source member.
    if expected_files.keys().ne(current_documents.keys()) {
        return Err(error("authoritative World source inventory changed"));
    }
    for (path, expected) in &expected_files {
        if canonical(expected)? != canonical(&current_documents[path])? {
            return Err(error(format!("unsupported World change in {path}")));
        }
    }
    // Additionally compare every typed part against baseline with positions
    // normalized back, including all fields/inventory/terrain/order.
    if current.profile() != baseline.world.profile()
        || current.definitions() != baseline.world.definitions()
    {
        return Err(error("unsupported profile/definition change"));
    }
    let mut planes = current.planes().clone();
    let plane = planes
        .get_mut("main")
        .ok_or_else(|| error("missing main plane"))?;
    let mut objects = BTreeMap::new();
    for chunk in plane.chunks.values_mut() {
        for object in chunk.objects.drain(..) {
            let uid = object.uid.clone().ok_or_else(|| error("UID-less object"))?;
            if objects.insert(uid, object).is_some() {
                return Err(error("duplicate UID"));
            }
        }
    }
    for m in &baseline.bundle.manifest.mappings {
        let mut object = objects
            .remove(&m.uid)
            .ok_or_else(|| error("missing object"))?;
        object.at = Some([
            u16::try_from(m.at[0] % 32).map_err(convert)?,
            u16::try_from(m.at[1] % 32).map_err(convert)?,
        ]);
        plane
            .chunks
            .get_mut(&(0, m.at[0] / 32, m.at[1] / 32))
            .ok_or_else(|| error("missing original chunk"))?
            .objects
            .push(object);
    }
    if !objects.is_empty() || &planes != baseline.world.planes() {
        return Err(error("unsupported full World semantic change"));
    }
    let mut transaction = Transaction::new(Arc::new(source.clone()));
    let mut replacements = Vec::new();
    for (original, moved) in baseline.bundle.manifest.mappings.iter().zip(&mappings) {
        for (axis, name, address) in [(0, "x", &original.x), (1, "y", &original.y)] {
            if original.at[axis] == moved.at[axis] {
                continue;
            }
            let address = address
                .as_ref()
                .ok_or_else(|| error("missing coordinate authority"))?;
            let before = std::str::from_utf8(&source.source_bytes()[address.start..address.end])
                .map_err(convert)?;
            let after = moved.at[axis].to_string();
            transaction
                .replace_value(address.record, after.as_bytes())
                .map_err(convert)?;
            replacements.push(Replacement {
                uid: original.uid.clone(),
                field: name.to_owned(),
                address: address.clone(),
                before: before.to_owned(),
                after,
            });
        }
    }
    replacements.sort_by_key(|r| r.address.start);
    let output = transaction.preview().map_err(convert)?;
    // Reimport the output, checking the same ordinal/semantic mapping policy.
    let mut identity = baseline.bundle.manifest.identity.clone();
    identity.original_sha256 = output.revision().to_string();
    let reimport = import_map(&output, identity)?;
    if reimport.world_files != expected_files {
        return Err(error(
            "export reimport differs from intended World projection",
        ));
    }
    verify_untouched(source.source_bytes(), output.source_bytes(), &replacements)?;
    Ok(ExportPreview {
        original_sha256: source.revision().to_string(),
        world_sha256: hex(&expected_world),
        output_sha256: output.revision().to_string(),
        replacements,
        unsupported: baseline.bundle.manifest.unsupported.clone(),
        bytes: output.source_bytes().to_vec(),
    })
}
fn canonical(bytes: &[u8]) -> Result<String> {
    let text = std::str::from_utf8(bytes).map_err(convert)?;
    let d = tilewright_jsonc::Document::parse(text, &world_options().limits).map_err(convert)?;
    Ok(d.canonical(d.root()))
}
fn verify_untouched(before: &[u8], after: &[u8], replacements: &[Replacement]) -> Result<()> {
    let (mut b, mut a) = (0usize, 0usize);
    for r in replacements {
        if r.address.start < b || r.address.end > before.len() {
            return Err(error("overlapping/outside export replacement"));
        }
        let n = r.address.start - b;
        if after.get(a..a + n) != Some(&before[b..r.address.start]) {
            return Err(error("untouched export bytes changed"));
        }
        a += n;
        if after.get(a..a + r.after.len()) != Some(r.after.as_bytes()) {
            return Err(error("replacement verification failed"));
        }
        a += r.after.len();
        b = r.address.end;
    }
    if after.get(a..) != Some(&before[b..]) {
        return Err(error("untouched export suffix changed"));
    }
    Ok(())
}
#[must_use]
pub fn hex(bytes: &[u8; 32]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}
pub fn parse_digest(text: &str) -> Result<[u8; 32]> {
    if text.len() != 64
        || !text
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
    {
        return Err(error("expected full lowercase SHA-256"));
    }
    let mut result = [0u8; 32];
    for (i, b) in result.iter_mut().enumerate() {
        *b = u8::from_str_radix(&text[i * 2..i * 2 + 2], 16).map_err(convert)?;
    }
    Ok(result)
}

